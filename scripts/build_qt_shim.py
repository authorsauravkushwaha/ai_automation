#!/usr/bin/env python3
"""Build minimal stub libraries so PySide6 can run headless without GPU/DBus.

Why this exists
---------------
The GUI tests (``tests/test_gui.py``) are real Qt tests: they construct
``MainWindow``, the dialogs and the control centre, and drive them through Qt's
``offscreen`` platform. On a minimal container that is impossible out of the
box, because ``libQt6Gui`` links against four shared libraries that are not
present and cannot be installed without a package network::

    libGL.so.1  libEGL.so.1  libxkbcommon.so.0  libdbus-1.so.3

The ``offscreen`` platform never *calls* into GL or DBus, but the dynamic
loader still resolves every symbol those libraries export. Supplying stubs
whose symbols exist (with the right versions) and return zero satisfies the
loader; nothing offscreen ever invokes them.

This is a **test-environment** workaround, not a shipping dependency. On a
normal desktop the real libraries are present and this script is unnecessary.

Usage
-----
    python scripts/build_qt_shim.py            # writes ./qt-shim
    export LD_LIBRARY_PATH="$PWD/qt-shim:$LD_LIBRARY_PATH"
    QT_QPA_PLATFORM=offscreen python scripts/run_tests.py

Requires gcc. Prints the exact export lines to use.
"""

from __future__ import annotations

import argparse
import importlib.util
import pathlib
import re
import shutil
import subprocess
import sys

#: Libraries Qt6Gui requires at load time on Linux.
STUB_TARGETS = ("libGL.so.1", "libEGL.so.1", "libxkbcommon.so.1", "libdbus-1.so.3")

#: Map the symbol-version labels ldd reports onto the library that must carry them.
VERSION_TO_LIBRARY = {
    "V_0.5.0": "libxkbcommon.so.0",
    "LIBDBUS_1_3": "libdbus-1.so.3",
}


def qt_library_dir() -> pathlib.Path:
    spec = importlib.util.find_spec("PySide6")
    if spec is None or not spec.origin:
        raise SystemExit("PySide6 is not installed; nothing to shim.")
    return pathlib.Path(spec.origin).parent / "Qt" / "lib"


def undefined_symbols(library: pathlib.Path, search_path: str) -> dict[str, str | None]:
    """Symbols ``library`` imports but cannot resolve, with their version label.

    ``ldd -r`` is unusable here: it prints only the *first* unresolved symbol
    per library, which silently hides the rest. ``nm -D --undefined-only``
    lists every import, and libc's resolver is not involved.
    """
    result = subprocess.run(
        ["nm", "-D", "--undefined-only", "--with-symbol-versions", str(library)],
        capture_output=True,
        text=True,
        check=False,
        timeout=30,
        env={"LD_LIBRARY_PATH": search_path},
    )
    found: dict[str, str | None] = {}
    for line in result.stdout.splitlines():
        # "                 U symbol@VERSION" or "                 U symbol"
        match = re.search(r"\bU\s+(\w+)(?:@(\S+))?\s*$", line)
        if not match:
            continue
        symbol, version = match.group(1), match.group(2)
        # Qt target libraries carry their own versioned tag (e.g. @Qt_6); those
        # resolve inside Qt itself and must not be stubbed.
        if version is not None and version.startswith("Qt_"):
            continue
        found.setdefault(symbol, version)
    return found


def unresolved_in_any(libraries: list[pathlib.Path], search_path: str) -> dict[str, str | None]:
    """Union of unresolved imports across all targets."""
    found: dict[str, str | None] = {}
    for library in libraries:
        if not library.exists():
            continue
        for symbol, version in undefined_symbols(library, search_path).items():
            found.setdefault(symbol, version)
    return found


def build_library(
    out_dir: pathlib.Path,
    name: str,
    symbols: list[str],
    version_label: str | None,
) -> None:
    """Compile a shared object exporting ``symbols`` as functions returning 0."""
    if not symbols:
        return
    symbols = sorted(set(symbols))
    source = out_dir / f"{name}.c"
    source.write_text(
        f"/* Generated by scripts/build_qt_shim.py -- {len(symbols)} stubs for {name}.\n"
        "   Offscreen Qt never calls these; they exist so the dynamic loader resolves. */\n"
        + "\n".join(f"long {symbol}(void) {{ return 0; }}" for symbol in symbols)
        + "\n",
        encoding="utf-8",
    )
    command = [
        "gcc", "-shared", "-fPIC", str(source),
        "-o", str(out_dir / name), "-Wl,-soname," + name,
    ]
    if version_label:
        version_file = out_dir / f"{name}.map"
        entries = "\n".join(f"\t{symbol};" for symbol in symbols)
        version_file.write_text(f"{version_label} {{\n{entries}\n}};\n", encoding="utf-8")
        command += ["-Wl,--version-script", str(version_file)]
    subprocess.run(command, check=True)
    print(f"  built {name:24} {len(symbols):4} symbols  version={version_label}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="qt-shim", help="output directory")
    args = parser.parse_args()

    if shutil.which("gcc") is None:
        raise SystemExit("gcc is required to build the shim.")

    out_dir = pathlib.Path(args.out).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    library_dir = qt_library_dir()

    targets = [
        library_dir / "libQt6Gui.so.6",
        library_dir / "libQt6DBus.so.6",
        library_dir / "libQt6OpenGL.so.6",
        library_dir.parent / "plugins" / "platforms" / "libqoffscreen.so",
    ]
    grouped: dict[tuple[str, str | None], list[str]] = {}

    def scan() -> dict[str, str | None]:
        return unresolved_in_any(targets, str(out_dir))

    # ``ldd -r`` only reports symbols whose owning library it can attribute, and
    # it cannot attribute anything until the *previous* layer resolves. Iterate
    # to a fixpoint: rebuild, rescan, and stop when a pass adds nothing new.
    print(f"Writing stubs to {out_dir}")
    for pass_number in range(1, 6):
        added = 0
        for symbol, version in scan().items():
            if version in VERSION_TO_LIBRARY:
                key = (VERSION_TO_LIBRARY[version], version)
            elif version is not None:
                continue
            elif symbol.startswith("egl"):
                key = ("libEGL.so.1", None)
            elif symbol.startswith(("gl", "glX")):
                key = ("libGL.so.1", None)
            elif symbol.startswith("xkb"):
                key = ("libxkbcommon.so.0", "V_0.5.0")
            else:
                continue
            if symbol not in grouped.get(key, []):
                grouped.setdefault(key, []).append(symbol)
                added += 1
        for (name, version), symbols in sorted(grouped.items()):
            build_library(out_dir, name, symbols, version)
        if not added:
            print(f"  stable after {pass_number} pass(es)")
            break

    if not grouped:
        print("Nothing to shim: Qt already resolves its dependencies here.")
        return 0

    print("\nAdd this to the environment before running the GUI tests:")
    print(f"  export LD_LIBRARY_PATH={out_dir}:$LD_LIBRARY_PATH")
    print("  export QT_QPA_PLATFORM=offscreen")
    return 0


if __name__ == "__main__":
    sys.exit(main())
